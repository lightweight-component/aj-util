package com.ajaxjs.util.httpremote.model;

/**
 * Enumeration of HTTP methods supported by the client.
 * Includes all standard HTTP methods.
 */
public enum HttpMethod {
    /**
     * GET method.
     */
    GET,

    /**
     * POST method.
     */
    POST,

    /**
     * PUT method.
     */
    PUT,

    /**
     * DELETE method.
     */
    DELETE,

    /**
     * HEAD method.
     */
    HEAD,

    /**
     * OPTIONS method.
     */
    OPTIONS,

    /**
     * PATCH method
     */
    PATCH,

    /**
     * TRACE method.
     */
    TRACE,

    /**
     * CONNECT method.
     */
    CONNECT
}